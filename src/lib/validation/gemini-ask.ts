import { z } from 'zod'

export const AskResponseSchema = z.object({
  answer: z.string().describe('The generated natural language answer derived strictly from evidence'),
  evidence_ids: z.array(z.string()).describe('List of EVIDENCE_X strings corresponding to the specific evidence used'),
  facts: z.array(z.string()).describe('Facts directly supported by evidence'),
  inferences: z.array(z.string()).describe('Reasonable conclusions derived from evidence'),
  recommendations: z.array(z.object({
    category: z.string(),
    items: z.array(z.string())
  })).describe('Useful suggestions generated by TRACE from context')
})

export type AskResponse = z.infer<typeof AskResponseSchema>
